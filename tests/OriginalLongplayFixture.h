inline void check_workforce(const sim::World& world,bool per_owner=false) {
    std::vector<const sim::BuildingState*> ordered;
    for (const auto& b:world.buildings()) if (world.workforce_required(b.id)>0 &&
        (!sim::World::operation_controllable(b.kind) || (b.operating_enabled && !world.building_on_fire(b.id)))) ordered.push_back(&b);
    std::stable_sort(ordered.begin(),ordered.end(),[](const auto* a,const auto* b) {
        return std::tie(a->workforce_priority,a->id)<std::tie(b->workforce_priority,b->id);
    });
    int available=world.total_population(),assigned=0;
    std::set<sim::BuildingId> staffed;
    for (const auto* b:ordered) if (const auto need=world.workforce_required(b->id);need<=available) {
        available-=need;assigned+=need;staffed.insert(b->id);
    }
    check(world.workforce_supply()==world.total_population() && world.workforce_used()==assigned,
          "Full paid city workforce differs from independent priority/ID/all-or-nothing allocation");
    if (per_owner) for (const auto& b:world.buildings())
        check(world.workers_assigned(b.id)==(staffed.contains(b.id)?world.workforce_required(b.id):0),
              "Actual assigned workers differ at an individual paid owner");
}

