inline std::size_t cell_index(const sim::World& world,sim::Cell cell) {
    return static_cast<std::size_t>(cell.y)*static_cast<std::size_t>(world.width())+
        static_cast<std::size_t>(cell.x);
}

// The exact public transport predicates include imported roads, fixed passages,
// signed-height edges and every policy blocker. Components are QA observations,
// never routes supplied back to the World.
inline std::vector<int> transport_components(const sim::World& world) {
    std::vector<int> components(static_cast<std::size_t>(world.width()*world.height()),-1);
    constexpr std::array<sim::Cell,4> steps{{{1,0},{0,1},{-1,0},{0,-1}}};
    int next=0;
    for (int y=0;y<world.height();++y) for (int x=0;x<world.width();++x) {
        const sim::Cell start{x,y};
        if (!world.transport_cell(start) || components[cell_index(world,start)]>=0) continue;
        std::deque<sim::Cell> pending{start};components[cell_index(world,start)]=next;
        while (!pending.empty()) {
            const auto at=pending.front();pending.pop_front();
            for (const auto step:steps) {
                const sim::Cell to{at.x+step.x,at.y+step.y};
                if (!world.in_bounds(to) || components[cell_index(world,to)]>=0 ||
                    !world.transport_edge_allowed(at,to)) continue;
                components[cell_index(world,to)]=next;pending.push_back(to);
            }
        }
        ++next;
    }
    return components;
}

inline int body_component(const sim::World& world,const std::vector<int>& components,
                          sim::BuildingId id) {
    std::optional<int> found;
    for (const auto& entrance:world.building_entrances(id)) {
        const auto component=components[cell_index(world,entrance.road_cell)];
        check(component>=0,"Paid district entrance is not in the actual transport graph");
        check(!found || *found==component,"One paid body joins two transport components");
        found=component;
    }
    check(found.has_value(),"Paid full-capacity body has no actual road entrance");
    return *found;
}

inline Scene classify(const sim::World& world) {
    check(world.original_production_enabled() && world.buildings().size()==82 && world.couriers().size()==58,
          "District classification requires the actual paid82/58 city");
    const auto components=transport_components(world);
    std::map<int,std::vector<sim::BuildingId>> groups;
    for (const auto& b:world.buildings()) groups[body_component(world,components,b.id)].push_back(b.id);
    check(groups.size()==2,"Paid82/58 city does not contain two independent transport districts");
    Scene result;std::size_t index=0;
    for (const auto& [component,ids]:groups) {
        (void)component;result.districts[index]=ids;
        sim::Cell minimum{world.width(),world.height()};
        for (const auto id:ids) {
            const auto& b=world.building(id);
            minimum.x=std::min(minimum.x,b.cell.x);minimum.y=std::min(minimum.y,b.cell.y);
            if (sim::original_house_kind(b.kind)) result.houses[index].push_back(id);
        }
        result.origins[index]=minimum;++index;
    }
    if (std::tie(result.origins[1].y,result.origins[1].x)<std::tie(result.origins[0].y,result.origins[0].x)) {
        std::swap(result.origins[0],result.origins[1]);
        std::swap(result.districts[0],result.districts[1]);std::swap(result.houses[0],result.houses[1]);
    }
    for (std::size_t district=0;district<2;++district)
        check(result.districts[district].size()==41 && result.houses[district].size()==10,
              "Paid district has a wrong body/House count");
    result.paid_cost=world.construction_spent_total();result.commands=world.command_sequence();
    return result;
}

inline std::size_t district_of(const Scene& scene,sim::BuildingId id) {
    for (std::size_t district=0;district<2;++district)
        if (std::find(scene.districts[district].begin(),scene.districts[district].end(),id)!=scene.districts[district].end())
            return district;
    throw std::runtime_error("Transport references a body outside the earned district membership");
}

inline void assert_independent(const sim::World& world,const Scene& scene) {
    const auto components=transport_components(world);
    std::array<int,2> selected{};
    for (std::size_t district=0;district<2;++district) {
        check(scene.districts[district].size()==41 && scene.houses[district].size()==10,
              "Independent district membership is incomplete");
        selected[district]=body_component(world,components,scene.districts[district].front());
        for (const auto id:scene.districts[district])
            check(body_component(world,components,id)==selected[district],"District body leaves its actual transport component");
    }
    check(selected[0]!=selected[1],"Original roads/gates or paid roads connect the two districts");
    const auto path_component=[&](const auto& path,std::size_t district) {
        for (std::size_t vertex=1;vertex+1<path.size();++vertex)
            check(world.in_bounds(path[vertex]) && components[cell_index(world,path[vertex])]==selected[district],
                  "Cached or active route enters another transport component");
    };
    for (const auto& actor:world.couriers()) {
        const auto district=district_of(scene,actor.owner);
        for (const auto& [target,route]:actor.dynamic_target_routes) {
            const bool same=district_of(scene,target)==district;
            check(same || !route,"Cached route crosses paid district boundary");
            if (route) path_component(*route,district);
        }
        if (!actor.path.empty()) {
            check(district_of(scene,actor.target)==district,"Actual courier target crosses district boundary");
            path_component(actor.path,district);
        }
    }
    const auto same_pair=[&](sim::BuildingId source,sim::BuildingId target) {
        check(district_of(scene,source)==district_of(scene,target),"Actual typed transfer crosses district boundary");
    };
    for (const auto& row:world.original_goods_state()->reservations) same_pair(row.source,row.target);
    const auto& state=*world.original_production_state();
    for (const auto& row:state.food.trips) same_pair(row.source,row.target);
    for (const auto& row:state.industry.aux_trips) same_pair(row.source,row.target);
}

inline std::array<sim::Cell,2> district_origins(const sim::World& world) {
    const int stride=world.width()+1;
    std::vector<int> blocked(static_cast<std::size_t>((world.width()+1)*(world.height()+1)));
    const auto prefix=[&](int x,int y)->int& {return blocked[static_cast<std::size_t>(y*stride+x)];};
    for (int y=0;y<world.height();++y) for (int x=0;x<world.width();++x) {
        const sim::Cell cell{x,y};
        const bool unsafe=!world.buildable(cell) || !world.road_buildable(cell) ||
            world.object_at(cell)!=sim::Object::Empty || world.transport_cell(cell);
        prefix(x+1,y+1)=int(unsafe)+prefix(x,y+1)+prefix(x+1,y)-prefix(x,y);
    }
    std::vector<sim::Cell> legal;
    for (int y=1;y+district_height<world.height();++y)
        for (int x=1;x+district_width<world.width();++x) {
            const int x1=x-1,y1=y-1,x2=x+district_width+1,y2=y+district_height+1;
            if (prefix(x2,y2)-prefix(x1,y2)-prefix(x2,y1)+prefix(x1,y1)) continue;
            const auto level=world.map_permissions()->cell_height({x,y});bool flat=true;
            for (int row=y1;row<y2 && flat;++row) for (int col=x1;col<x2;++col)
                if (world.map_permissions()->cell_height({col,row})!=level) {flat=false;break;}
            if (flat) legal.push_back({x,y});
        }
    const auto distance=[&](sim::Cell cell) {
        return std::abs(2*cell.x+district_width-world.width())+
            std::abs(2*cell.y+district_height-world.height());
    };
    std::stable_sort(legal.begin(),legal.end(),[&](auto a,auto b){return distance(a)<distance(b);});
    const auto separate=[](sim::Cell a,sim::Cell b) {
        return a.x+district_width+2<=b.x || b.x+district_width+2<=a.x ||
            a.y+district_height+2<=b.y || b.y+district_height+2<=a.y;
    };
    if (!legal.empty()) {
        for (const auto b:legal) if (separate(legal.front(),b)) return {legal.front(),b};
        // Equal-sized axis-aligned rectangles can be separated iff the range
        // of their legal x or y origins is wide enough. Extremes avoid an
        // unbounded all-pairs search when a real map has only one clear patch.
        const auto [left,right]=std::minmax_element(legal.begin(),legal.end(),[](auto a,auto b){return a.x<b.x;});
        if (separate(*left,*right)) return {*left,*right};
        const auto [top,bottom]=std::minmax_element(legal.begin(),legal.end(),[](auto a,auto b){return a.y<b.y;});
        if (separate(*top,*bottom)) return {*top,*bottom};
    }
    throw std::runtime_error("No pair of legal empty32x22 level districts with clean transport-isolating rings");
}

